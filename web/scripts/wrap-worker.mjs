import { existsSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { relative, resolve, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const defaultOutput = fileURLToPath(
  new URL("../.svelte-kit/cloudflare/", import.meta.url),
);
const scheduled = fileURLToPath(
  new URL("../src/worker/scheduled.ts", import.meta.url),
);
const generatedHeader = "// Generated by scripts/wrap-worker.mjs.";

export function wrapWorker(output = defaultOutput) {
  const entry = resolve(output, "_worker.js");
  const kitEntry = resolve(output, "_kit_worker.js");
  const assetsIgnore = resolve(output, ".assetsignore");
  const ignored = readFileSync(assetsIgnore, "utf8");
  const lines = ignored.split(/\r?\n/);
  if (!lines.includes("_worker.js"))
    throw new Error("_worker.js must be excluded from Worker assets.");

  if (readFileSync(entry, "utf8").startsWith(generatedHeader)) {
    if (!existsSync(kitEntry) || !lines.includes("_kit_worker.js")) {
      throw new Error("The wrapped Worker entry is incomplete.");
    }
    return;
  }

  const withKit = lines.includes("_kit_worker.js")
    ? ignored
    : `${ignored}\n_kit_worker.js\n`;
  writeFileSync(assetsIgnore, withKit);
  renameSync(entry, kitEntry);

  const scheduledPath = relative(output, scheduled).split(sep).join("/");
  writeFileSync(
    entry,
    `${generatedHeader}
import kit from "./_kit_worker.js";
import { scheduled } from ${JSON.stringify(scheduledPath.startsWith(".") ? scheduledPath : "./" + scheduledPath)};
export default { fetch: kit.fetch, scheduled };
`,
  );
}

if (
  process.argv[1] &&
  pathToFileURL(resolve(process.argv[1])).href === import.meta.url
) {
  wrapWorker();
}
